-- paychaos schema. Hand-written SQL, applied in file-name order by
-- src/migrate.ts; each file runs once, inside a transaction.

CREATE TABLE projects (
  id          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name        text NOT NULL UNIQUE CHECK (length(name) BETWEEN 1 AND 100),
  created_at  timestamptz NOT NULL DEFAULT now()
);

-- Ingest tokens are stored as SHA-256 hashes. The plaintext is shown once,
-- when the token is created. `prefix` is the first characters, kept so a
-- person can tell tokens apart in the dashboard.
CREATE TABLE ingest_tokens (
  id          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  project_id  uuid NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  label       text NOT NULL DEFAULT '',
  prefix      text NOT NULL,
  token_hash  bytea NOT NULL UNIQUE,
  created_at  timestamptz NOT NULL DEFAULT now(),
  revoked_at  timestamptz
);
CREATE INDEX ingest_tokens_project ON ingest_tokens (project_id);

CREATE TABLE scenarios (
  id          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  project_id  uuid NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  name        text NOT NULL CHECK (length(name) BETWEEN 1 AND 100),
  config      jsonb NOT NULL,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now(),
  UNIQUE (project_id, name)
);

-- A run's id is generated by the engine, so creating it is an idempotent PUT.
CREATE TABLE runs (
  id              uuid PRIMARY KEY,
  project_id      uuid NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  name            text NOT NULL DEFAULT '',
  seed            numeric(20, 0) NOT NULL,       -- a Go uint64
  upstream        text NOT NULL,
  scenario        jsonb NOT NULL DEFAULT '{}',
  engine_version  text NOT NULL DEFAULT '',
  status          text NOT NULL DEFAULT 'running' CHECK (status IN ('running', 'finished')),
  started_at      timestamptz NOT NULL,
  finished_at     timestamptz,
  request_count   integer NOT NULL DEFAULT 0,
  high            integer NOT NULL DEFAULT 0,
  medium          integer NOT NULL DEFAULT 0,
  low             integer NOT NULL DEFAULT 0,
  faults_applied  jsonb NOT NULL DEFAULT '{}',
  webhooks        jsonb NOT NULL DEFAULT '[]',
  webhook_notes   jsonb NOT NULL DEFAULT '[]'
);
-- Serves the keyset-paginated run list:
--   WHERE project_id = $1 AND (started_at, id) < ($2, $3)
--   ORDER BY started_at DESC, id DESC
CREATE INDEX runs_project_started ON runs (project_id, started_at DESC, id DESC);

-- One row per ingested batch. The primary key is what makes ingest
-- retry-safe: a batch sent twice inserts nothing the second time.
CREATE TABLE ingest_batches (
  run_id       uuid NOT NULL REFERENCES runs(id) ON DELETE CASCADE,
  seq          integer NOT NULL CHECK (seq > 0),
  event_count  integer NOT NULL,
  received_at  timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (run_id, seq)
);

-- Audited requests. A record can arrive twice (completed, then marked
-- delivered), so its key is (run_id, seq) and later versions update it.
CREATE TABLE requests (
  run_id              uuid NOT NULL REFERENCES runs(id) ON DELETE CASCADE,
  seq                 integer NOT NULL,
  at                  timestamptz NOT NULL,
  done                timestamptz,
  method              text NOT NULL,
  path                text NOT NULL,
  operation           text NOT NULL DEFAULT '',
  request_id          text NOT NULL DEFAULT '',
  fingerprint         text NOT NULL,
  rule                text NOT NULL DEFAULT '',
  fault               text NOT NULL DEFAULT 'none',
  upstream_status     integer NOT NULL DEFAULT 0,
  issue               text NOT NULL DEFAULT '',
  object_id           text NOT NULL DEFAULT '',
  committed           boolean NOT NULL DEFAULT false,
  response_delivered  boolean NOT NULL DEFAULT false,
  PRIMARY KEY (run_id, seq)
);
CREATE INDEX requests_run_fingerprint ON requests (run_id, fingerprint, seq);

-- Findings streamed during a run are provisional (final = false). The finish
-- message replaces them with the complete list (final = true), because some
-- findings can only be decided once traffic has stopped.
CREATE TABLE findings (
  id           bigserial PRIMARY KEY,
  run_id       uuid NOT NULL REFERENCES runs(id) ON DELETE CASCADE,
  code         text NOT NULL,
  severity     text NOT NULL CHECK (severity IN ('HIGH', 'MEDIUM', 'LOW')),
  message      text NOT NULL,
  path         text NOT NULL DEFAULT '',
  operation    text NOT NULL DEFAULT '',
  fingerprint  text NOT NULL DEFAULT '',
  requests     integer[] NOT NULL DEFAULT '{}',
  object_ids   text[] NOT NULL DEFAULT '{}',
  at           timestamptz NOT NULL,
  final        boolean NOT NULL DEFAULT false
);
CREATE INDEX findings_run ON findings (run_id, severity);

CREATE TABLE webhook_deliveries (
  run_id           uuid NOT NULL REFERENCES runs(id) ON DELETE CASCADE,
  delivered_order  integer NOT NULL,
  event_id         text NOT NULL,
  type             text NOT NULL DEFAULT '',
  copy             integer NOT NULL DEFAULT 0,
  received_order   integer NOT NULL,
  status           integer NOT NULL DEFAULT 0,
  error            text NOT NULL DEFAULT '',
  at               timestamptz NOT NULL,
  PRIMARY KEY (run_id, delivered_order)
);
